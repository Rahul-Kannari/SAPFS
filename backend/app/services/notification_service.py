"""
Email & In-App Notification Service
Handles: Risk alerts, attendance warnings, assignment reminders
"""
import logging
from typing import List, Optional, Dict
from datetime import datetime

logger = logging.getLogger(__name__)

class NotificationService:
    """Unified notification service for email and in-app alerts"""
    
    def __init__(self):
        self.email_enabled = False  # Set True when SMTP configured
    
    async def send_risk_alert(self, student_email: str, student_name: str,
                              risk_level: str, predicted_gpa: float,
                              recommendations: List[str]) -> bool:
        """Send risk level alert to student and faculty"""
        subject = f"⚠️ Academic Risk Alert — {student_name}"
        body = self._build_risk_email(student_name, risk_level, predicted_gpa, recommendations)
        return await self._send_email(student_email, subject, body)
    
    async def send_attendance_warning(self, student_email: str, student_name: str,
                                      attendance_pct: float, course_name: str) -> bool:
        """Send attendance warning when below threshold"""
        subject = f"📅 Attendance Warning — {course_name}"
        body = self._build_attendance_email(student_name, attendance_pct, course_name)
        return await self._send_email(student_email, subject, body)
    
    async def send_assignment_reminder(self, student_emails: List[str],
                                       assignment_title: str, due_date: datetime,
                                       course_name: str) -> int:
        """Send bulk assignment deadline reminders"""
        subject = f"📝 Assignment Due: {assignment_title} — {course_name}"
        sent_count = 0
        for email in student_emails:
            body = self._build_assignment_email(assignment_title, due_date, course_name)
            if await self._send_email(email, subject, body):
                sent_count += 1
        return sent_count
    
    async def send_prediction_report(self, recipient_email: str,
                                     student_name: str, pdf_bytes: bytes) -> bool:
        """Send prediction report as email attachment"""
        subject = f"🤖 AI Prediction Report — {student_name}"
        body = f"Dear Faculty,\n\nPlease find attached the AI prediction report for {student_name}.\n\nGenerated by SAPFS v1.0"
        return await self._send_email(recipient_email, subject, body, attachment=pdf_bytes)
    
    def _build_risk_email(self, name: str, risk: str, gpa: float, recs: List[str]) -> str:
        risk_emoji = {'low': '✅', 'medium': '⚠️', 'high': '🚨', 'critical': '🔴'}
        rec_text = '\n'.join([f"  • {r}" for r in recs[:5]])
        return f"""
Dear {name},

{risk_emoji.get(risk, '⚠️')} ACADEMIC RISK ALERT

Your AI-generated academic risk assessment has been updated:

Risk Level:      {risk.upper()}
Predicted GPA:   {gpa:.2f} / 10.00
Assessment Date: {datetime.now().strftime('%d %B %Y')}

RECOMMENDED ACTIONS:
{rec_text}

Please visit the SAPFS portal for detailed insights and contact your academic advisor.

Best regards,
Smart Academic Performance Forecasting System (SAPFS)
        """.strip()
    
    def _build_attendance_email(self, name: str, pct: float, course: str) -> str:
        return f"""
Dear {name},

📅 ATTENDANCE WARNING — {course}

Your current attendance in {course} is {pct:.1f}%, which is below the required minimum of 75%.

ACTION REQUIRED:
• Attendance below 75% may result in exam debarment
• Please attend all remaining classes immediately
• Contact your faculty if you have medical/emergency absences

Current Status: {pct:.1f}% ({'⚠️ Warning' if pct >= 65 else '🚨 Critical — Debarment Risk'})

Log in to SAPFS for detailed attendance records.

Best regards,
SAPFS Notification System
        """.strip()
    
    def _build_assignment_email(self, title: str, due: datetime, course: str) -> str:
        return f"""
📝 ASSIGNMENT DEADLINE REMINDER

Assignment: {title}
Course:     {course}
Due Date:   {due.strftime('%d %B %Y, %I:%M %p')}

Please ensure your submission is uploaded to the SAPFS portal before the deadline.
Late submissions may receive reduced marks or be rejected.

Login at: http://localhost:3000

Best regards,
SAPFS Notification System
        """.strip()
    
    async def _send_email(self, to: str, subject: str, body: str,
                          attachment: Optional[bytes] = None) -> bool:
        """Send email via SMTP (stub — configure SMTP settings to enable)"""
        if not self.email_enabled:
            logger.info(f"[EMAIL STUB] To: {to} | Subject: {subject}")
            return True
        
        try:
            import aiosmtplib
            from email.mime.text import MIMEText
            from email.mime.multipart import MIMEMultipart
            from app.core.config import settings
            
            msg = MIMEMultipart()
            msg['From'] = settings.EMAIL_FROM
            msg['To'] = to
            msg['Subject'] = subject
            msg.attach(MIMEText(body, 'plain'))
            
            if attachment:
                from email.mime.application import MIMEApplication
                part = MIMEApplication(attachment, Name='report.pdf')
                part['Content-Disposition'] = 'attachment; filename="report.pdf"'
                msg.attach(part)
            
            await aiosmtplib.send(
                msg,
                hostname=settings.SMTP_HOST,
                port=settings.SMTP_PORT,
                username=settings.SMTP_USER,
                password=settings.SMTP_PASSWORD,
                start_tls=True,
            )
            logger.info(f"Email sent to {to}: {subject}")
            return True
        except Exception as e:
            logger.error(f"Email failed to {to}: {e}")
            return False

# Singleton instance
notification_service = NotificationService()


async def create_in_app_notification(db, user_id, title: str, message: str,
                                      notif_type: str = "general", priority: int = 1,
                                      metadata: Optional[Dict] = None):
    """Create an in-app notification record"""
    from app.models.models import Notification
    notif = Notification(
        user_id=user_id,
        title=title,
        message=message,
        notification_type=notif_type,
        priority=priority,
        notification_metadata=metadata or {}
    )
    db.add(notif)
    await db.flush()
    return notif
